from ci_agent.code.go_outline import go_subtest_key, outline_go_source, outline_unparsed
from ci_agent.tools.code_tools import resolve_symbol, symbol_containing

SRC = b'''package proxy

import (
\t"fmt"
\t"testing"
)

const (
\tKindTimeout = "timeout"
\tKindRefused = "refused"
)

type BackendError struct {
\tKind  string
\tMsg   string
}

func classifyBackendError(err error) string {
\tif err == nil {
\t\treturn ""
\t}
\treturn fmt.Sprintf("backend: %v", err)
}

func (s *Server) handleAuth(w int, r int) error {
\treturn nil
}

func TestReconcile(t *testing.T) {
\tt.Run("missing backend", func(t *testing.T) {
\t\tt.Fatal("boom")
\t})
\tt.Run("stale_endpoint", func(t *testing.T) {})
}

func TestTable(t *testing.T) {
\tcases := []struct {
\t\tname string
\t\twant int
\t}{
\t\t{
\t\t\tname: "empty input",
\t\t\twant: 0,
\t\t},
\t\t{
\t\t\tname: "one item",
\t\t\twant: 1,
\t\t},
\t}
\tfor _, tc := range cases {
\t\tt.Run(tc.name, func(t *testing.T) {
\t\t\t_ = tc.want
\t\t})
\t}
}
'''


def outline():
    return outline_go_source(SRC, "pkg/proxy/route.go", "deadbeef" * 5)


def test_kinds_and_names():
    names = {s.name: s.kind for s in outline().symbols}
    assert names["classifyBackendError"] == "func"
    assert names["(*Server).handleAuth"] == "method"   # spelled as a panic frame does
    assert names["TestReconcile"] == "test"
    assert names["BackendError"] == "type"
    assert names["imports"] == "imports"


def test_never_returns_source():
    rendered = outline().render()
    assert "Sprintf" not in rendered and "t.Fatal" not in rendered


def test_subtest_names_are_go_normalised():
    reconcile = resolve_symbol(outline(), "TestReconcile")
    got = {c.name: c.heuristic for c in reconcile.children}
    # `t.Run("missing backend")` prints as TestReconcile/missing_backend
    assert got == {"missing_backend": False, "stale_endpoint": False}


def test_go_subtest_key_matches_testing_rewrite():
    assert go_subtest_key("missing backend") == "missing_backend"
    assert go_subtest_key("a\tb") == "a\\x09b"


def test_table_driven_cases_are_recovered_as_heuristic():
    table = resolve_symbol(outline(), "TestTable")
    cases = {c.name: c for c in table.children}
    assert set(cases) == {"empty_input", "one_item"}
    assert all(c.heuristic for c in cases.values())
    # the span is the case's own literal, not the shared t.Run body
    assert cases["empty_input"].end_line - cases["empty_input"].start_line < 6


def test_addressing_by_failure_text():
    o = outline()
    sym = resolve_symbol(o, "TestReconcile/missing_backend")
    assert sym.name == "missing_backend"
    assert resolve_symbol(o, "handleAuth").name == "(*Server).handleAuth"


def test_unknown_subtest_falls_back_to_parent():
    sym = resolve_symbol(outline(), "TestReconcile/renamed_since")
    assert sym.name == "TestReconcile"   # finest address available, not None


def test_symbol_at_line_picks_narrowest_span():
    o = outline()
    classify = resolve_symbol(o, "classifyBackendError")
    assert symbol_containing(o, classify.start_line + 1).name == "classifyBackendError"
    reconcile = resolve_symbol(o, "TestReconcile")
    sub = reconcile.children[0]
    assert symbol_containing(o, sub.start_line).name == "missing_backend"


def test_generated_marker():
    gen = b"// Code generated by controller-gen. DO NOT EDIT.\n\npackage v1\n"
    o = outline_go_source(gen, "api/v1/zz_generated.deepcopy.go", "abc")
    assert o.generated
    assert "generator" in o.render()


def test_parse_error_still_yields_symbols():
    broken = SRC + b"\nfunc Dangling( {\n"
    o = outline_go_source(broken, "pkg/proxy/route.go", "abc")
    assert o.rung == "partial"
    assert resolve_symbol(o, "classifyBackendError") is not None


def test_large_const_block_is_summarised():
    body = b"package x\n\nconst (\n" + b"".join(
        b'\tC%d = %d\n' % (i, i) for i in range(30)
    ) + b")\n"
    o = outline_go_source(body, "x.go", "abc")
    consts = [s for s in o.symbols if s.kind == "const"]
    assert len(consts) == 1 and "+29 more" in consts[0].name


def test_non_go_falls_to_sample_rung():
    o = outline_unparsed(b"a: 1\nb: 2\n", "config.yaml", "abc", reason="no grammar")
    assert o.rung == "unparsed" and o.sample and o.symbols == []


def test_outline_shrinks_a_large_file_by_an_order_of_magnitude():
    """The 15x claim is about 3 000-line files; a 55-line file wins nothing,
    which is why the fixture here is big."""
    body = b"package x\n\n" + b"".join(
        b"func F%d(a int) error {\n" % i + b"\tif err := doSomething(ctx, a, \"a reasonably typical line\"); err != nil {\n\t\treturn err\n\t}\n" * 14 + b"\treturn nil\n}\n\n"
        for i in range(60)
    )
    o = outline_go_source(body, "big.go", "abc")
    assert o.total_lines > 2500
    assert len(o.render()) < len(body) / 10
